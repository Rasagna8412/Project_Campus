"""Pydantic Schemas for AI Tutor, Quiz Generation, and Subscription Entitlements."""

import uuid
from typing import List, Optional
from pydantic import BaseModel, ConfigDict, Field


class ChatMessage(BaseModel):
    """Single turn in a bounded conversation history."""

    role: str = Field(..., description="Role of the sender ('user' or 'assistant')")
    content: str = Field(..., max_length=1000, description="Message content text")


class AITutorChatRequest(BaseModel):
    """Student query payload for the Campus AI Tutor."""

    message: str = Field(
        ...,
        min_length=1,
        max_length=1000,
        description="Student question, doubt, or request",
    )
    lesson_id: Optional[uuid.UUID] = Field(
        None, description="Optional active lesson UUID for grounding context"
    )
    topic_id: Optional[uuid.UUID] = Field(
        None, description="Optional curriculum topic UUID for broader topic context"
    )
    mode: str = Field(
        "EXPLAIN",
        description="Tutor explanation mode: EXPLAIN, SIMPLIFY, EXAMPLE, HINT, QUIZ",
    )
    history: Optional[List[ChatMessage]] = Field(
        None,
        max_length=4,
        description="Bounded prior conversation turns (maximum 4)",
    )


class AITutorQuizQuestion(BaseModel):
    """A single multiple-choice quiz question generated by the AI tutor."""

    question: str
    options: List[str]
    correct_index: int
    explanation: str


class AITutorChatResponse(BaseModel):
    """Grounded AI tutor response payload."""

    model_config = ConfigDict(from_attributes=True)

    response: str
    mode: str
    lesson_id: Optional[uuid.UUID] = None
    lesson_title: Optional[str] = None
    grounding_sources: List[str] = []
    quiz_questions: Optional[List[AITutorQuizQuestion]] = None
    provider: str
    tokens_used: int
    tier: str
    daily_quota: int
    daily_used: int
    daily_remaining: int


class SubscriptionEntitlementResponse(BaseModel):
    """Current student subscription tier and daily AI quota status."""

    model_config = ConfigDict(from_attributes=True)

    tier: str
    daily_tutor_quota: int
    daily_tutor_used: int
    daily_tutor_remaining: int
    is_unlimited: bool
    valid_until: Optional[str] = None
    features: List[str]


class TierUpgradeRequest(BaseModel):
    """Request payload for updating or testing tier status."""

    target_tier: str = Field("PRO", description="Target tier: FREE or PRO")
